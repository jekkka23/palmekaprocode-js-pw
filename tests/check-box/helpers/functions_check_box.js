//Чекбокс элемент с двумя состояниями: выбран или не выбран.

//Родительский пункт. чекбокс, который управляет вложенными пунктами. Здесь "Рабочий стол" управляет двумя дочерними галочками.

//check действие Playwright, которое выбирает чекбокс и дожидается результата действия.

//toBeChecked ассерт, который ждет выбранного состояния чекбокса.

//toHaveText ассерт, который сравнивает весь текст элемента с ожидаемой строкой.

import { test, expect } from "@playwright/test";
// import подключает test и expect из пакета "@playwright/test".
// фигурные скобки здесь означают, что мы берем их по именам.
// test.step() создает именованный шаг, а expect() нужен для проверок.


import { CheckBoxPage } from "../pages/check_box_page.js";
// CheckBoxPage - класс, в котором лежат локаторы и действия для этой страницы.
// ../ поднимает нас из папки helpers на уровень выше. Оттуда идем в папку pages.

export async function runCheckBoxCase(page) {
  // function объявляет функцию с именем runCheckBoxCase.
  // export позволяет импортировать ее в спеку и вызвать оттуда.
  // page - вкладка браузера, которую тест передает в функцию.
  // async позволяет использовать await внутри функции. Сама функция возвращает Promise.

  console.log("начинаем проверку дерева чекбоксов");
  console.log("создаем объект CheckBoxPage для текущей вкладки");
  const tree = new CheckBoxPage(page);
  // new создает объект CheckBoxPage и передает вкладку page в его constructor.
  // const объявляет переменную tree, а = сохраняет в нее созданный объект.
  console.log("объект CheckBoxPage создан");

  await test.step("Шаг 1. Открыть дерево чекбоксов", async () => {
    // первый аргумент test.step() - название шага, которое видно в отчете.
    // второй аргумент - асинхронная стрелочная функция с действиями этого шага.
    // await перед test.step() ждет завершения всего шага перед переходом к следующему.
    console.log("шаг 1. открываем дерево чекбоксов");

    console.log("шаг 1. переходим на /practice/check-box");
    await tree.open();
    // tree - наш объект страницы. Через точку вызываем его метод open().
    // await ждет, пока метод откроет страницу тренажера.
    console.log("шаг 1. страница тренажера открылась");

    console.log("шаг 1. проверяем, что заголовок \"Чекбоксы\" виден");
    await expect(tree.heading).toBeVisible();
    // tree.heading - локатор заголовка, который передаем в expect().
    // toBeVisible() проверяет, что заголовок виден. Playwright ждет выполнения условия до таймаута.
    console.log("шаг 1. заголовок 'Чекбоксы' виден");

    console.log("шаг 1. проверяем, что у пункта \"Рабочий стол\" изначально нет галочки");
    await expect(tree.desktop).not.toBeChecked();
    // tree.desktop - локатор чекбокса "Рабочий стол".
    // toBeChecked() проверяет галочку, а not переворачивает условие. Здесь ждем, что галочка снята.
    console.log("шаг 1. у пункта \"Рабочий стол\" галочка снята");
    console.log("шаг 1 завершен");
  });

  await test.step("Шаг 2. Выбрать Рабочий стол", async () => {
    // во втором шаге ставим галочку у родительского пункта.
    console.log("шаг 2. выбираем пункт \"Рабочий стол\"");

    console.log("шаг 2. вызываем selectDesktop()");
    await tree.selectDesktop();
    // вызываем метод selectDesktop() из CheckBoxPage. Внутри него check() ставит галочку.
    // await ждет завершения действия, прежде чем начнутся проверки результата.
    console.log("шаг 2. selectDesktop() завершился");
    console.log("шаг 2 завершен");
  });

  await test.step("Шаг 3. Проверить дочерние пункты и результат", async () => {
    // в третьем шаге проверяем галочки и текст результата после выбора "Рабочего стола".
    console.log("шаг 3. проверяем галочки и список выбранных пунктов");

    console.log("шаг 3. проверяем галочку у пункта \"Рабочий стол\"");
    await expect(tree.desktop).toBeChecked();
    // проверяем, что у "Рабочего стола" теперь стоит галочка.
    console.log("шаг 3. пункт \"Рабочий стол\" отмечен");

    console.log("шаг 3. проверяем галочку у пункта \"Заметки\"");
    await expect(tree.notes).toBeChecked();
    // tree.notes - локатор чекбокса "Заметки". Проверяем, что страница отметила и его.
    console.log("шаг 3. пункт \"Заметки\" отмечен");

    console.log("шаг 3. проверяем галочку у пункта \"Команды\"");
    await expect(tree.commands).toBeChecked();
    // tree.commands - локатор чекбокса "Команды". Проверяем его галочку отдельно.
    console.log("шаг 3. пункт \"Команды\" отмечен");

    console.log("шаг 3. ожидаем текст \"Рабочий стол, Заметки, Команды\"");
    await expect(tree.result).toHaveText("Рабочий стол, Заметки, Команды");
    // tree.result - локатор строки, в которой страница показывает выбранные пункты.
    // toHaveText() сравнивает весь текст строки с ожидаемым. Здесь важен и порядок пунктов.
    console.log("шаг 3. текст результата совпал, порядок пунктов верный");
    console.log("шаг 3 завершен");
  });

  console.log("все проверки дерева чекбоксов прошли");
}