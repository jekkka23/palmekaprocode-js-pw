

import { test, expect } from "@playwright/test";
// Подключаем именованные шаги и ассерты.
import { TextBoxPage } from "../pages/text_box_page.js";
// Из helpers переходим в соседнюю папку pages.
export async function runTextBoxCase(page, data) {
// Экспортируем один законченный флоу для спеки.


const form = new TextBoxPage(page);
  // Создаем объект страницы для вкладки текущего теста.

  await test.step("Шаг 1. Открыть текстовые поля", async () => {
    // test.step объединяет действия в один именованный шаг отчета Playwright.
    // "Шаг 1. Открыть текстовые поля" - название, которое вы увидите в отчете.
    // async позволяет использовать await внутри функции этого шага.

    //async - пометка перед функцией, которая разрешает использовать await внутри нее.
    //await означает: "дождись завершения этого действия, затем выполняй следующую строку".
    console.log("шаг 1. открываю тренажер текстовых полей");

    await form.open();
    // form - объект страницы с локаторами и методами работы с формой.
    // open() открывает тренажер, а await ждет завершения этого действия.

    await expect(form.heading).toBeVisible();
    // form.heading - локатор заголовка тренажера.
    // expect получает этот локатор, а toBeVisible() проверяет видимость заголовка.
    // проверка повторяется до успеха или истечения времени ожидания.
    console.log("шаг 1. тренажер открыт, заголовок виден");
  });

  await test.step("Шаг 2. Отправить имя и почту", async () => {
    // создаем следующий шаг того же теста.
    // он начнется после успешного завершения первого шага.
    console.log("шаг 2. отправляю имя и почту:", data.name, data.email);

    await form.submit(data.name, data.email);
    // data - объект с тестовыми данными.
    // data.name берет имя из этого объекта, а data.email - почту.
    // передаем оба значения в метод submit: сначала имя, затем почту.
    // метод заполняет поля и нажимает кнопку отправки.
    // await ждет завершения действий внутри submit.
    console.log("шаг 2. поля заполнены, кнопка отправки нажата");
  });

  await test.step("Шаг 3. Проверить результат", async () => {
    // после отправки проверяем данные, которые форма показала на странице.
    console.log("шаг 3. проверяю имя и почту в блоке результата");

    await expect(form.result).toContainText(data.name);
    // form.result - локатор блока результата.
    // toContainText ищет переданное имя как часть текста этого блока.
    // await ждет, пока проверка пройдет или закончится время ожидания.
    console.log("имя найдено в результате:", data.name);

    await expect(form.result).toContainText(data.email);
    // в том же блоке отдельно проверяем отправленную почту.
    // обе проверки используют данные, которые передали в form.submit.
    // если значение не появится за время ожидания, шаг и весь тест упадут.
    console.log("почта найдена в результате:", data.email);
    console.log("шаг 3. проверка результата прошла успешно");
  });
}
