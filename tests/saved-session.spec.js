import { test, expect } from "@playwright/test";
// import подключает инструменты из другого модуля, чтобы использовать их в этом файле.
// "@playwright/test" - пакет, из которого мы берем инструменты для запуска тестов и проверок.
// фигурные скобки здесь означают именованный импорт: мы выбираем конкретные экспорты пакета.
// test нужен для объявления теста: задаем название и функцию с действиями.
// expect нужен для проверок: например, что заголовок появился и виден на странице.
// после импорта test и expect можно использовать ниже по коду.
// точка с запятой завершает инструкцию импорта.

import { login } from "./helpers/login.js";
// подключаем нашу функцию login из отдельного файла.
// это тоже именованный импорт: в указанном файле должен быть экспорт с именем login.
// "./" означает, что путь начинается от папки текущего файла с тестом.
// "helpers" - вложенная папка, в которой находится файл login.js.
// если этот тест лежит в tests/saved-session.spec.js, путь ведет в tests/helpers/login.js.
// login - хелпер: функция, в которую вынесли повторяющиеся действия.
// благодаря этому действия входа можно использовать в разных тестах.
// импорт только делает функцию доступной. сам по себе он не вызывает login.
// конкретные действия внутри login определяются кодом файла login.js.

test("хелпер входа открывает тренажер", async ({ page }) => {
  // объявляем один тест через функцию test.
  // первый аргумент - название теста: "хелпер входа открывает тренажер".
  // это название будет видно в списке тестов и в результатах запуска.
  // название объясняет человеку, какое поведение проверяет тест.
  // второй аргумент - функция, внутри которой записаны действия и проверки.
  // playwright вызовет эту функцию, когда начнет выполнять данный тест.
  //
  // async делает функцию асинхронной и позволяет использовать внутри нее await.
  // такая функция возвращает промис, по которому playwright отслеживает ее завершение.
  // если внутри возникнет необработанная ошибка, тест завершится с ошибкой.
  //
  // playwright передает в функцию объект с доступными инструментами - фикстурами.
  // запись { page } достает из этого объекта свойство page в отдельную переменную.
  // такой способ получения свойства называется деструктуризацией.
  // здесь фигурные скобки достают значение из объекта, а в import они выбирали экспорты.
  //
  // page - объект для управления вкладкой браузера.
  // через него можно открывать страницы, находить элементы, вводить текст и нажимать кнопки.
  // playwright подготавливает page для теста, поэтому создавать вкладку вручную здесь не нужно.
  //
  // символы => обозначают стрелочную функцию.
  // открывающая фигурная скобка начинает тело функции - блок действий этого теста.

    await login(page);
  // вызываем импортированную функцию login.
  // круглые скобки после имени функции означают ее вызов.
  // внутри скобок передаем аргумент page - вкладку, с которой работает этот тест.
  // благодаря этому хелпер получает доступ к той же вкладке браузера.
  //
  // await ожидает завершения вызова, если login возвращает промис.
  // следующая строка этого теста начнет выполняться после успешного завершения login.
  // ожидание относится к этой асинхронной функции, а не останавливает весь javascript.
  //
  // чтобы ожидание работало правильно, login должен возвращать завершение своих действий.
  // обычно для этого сам хелпер объявляют через async и используют await внутри.
  // если login завершится с ошибкой, выполнение теста остановится на этой строке.
  //
  // по одному названию login нельзя определить, как именно устроен вход.
  // хелпер может заполнять форму, получать токен или использовать другой способ.
  // точный способ можно узнать только из его реализации в helpers/login.js.

    await page.goto("/practice/text-box");
  // вызываем метод goto у объекта page, чтобы открыть нужную страницу.
  // точка между page и goto означает обращение к методу объекта.
  // "/practice/text-box" - путь страницы, которую должен открыть браузер.
  //
  // здесь указан путь без протокола и домена, поэтому playwright нужен baseURL.
  // baseURL обычно задают в playwright.config.js в настройках use.
  // playwright объединяет baseURL с этим путем и получает полный адрес страницы.
  // начальный "/" означает путь от корня сайта.
  // без подходящего baseURL такой путь нельзя использовать как самостоятельный адрес.
  //
  // await ждет завершения перехода, прежде чем выполнять следующую строку теста.
  // по умолчанию goto ожидает событие load у открываемой страницы.
  // при этом отдельные элементы приложения могут появиться позже, например после загрузки данных.
  // поэтому после перехода мы отдельно проверяем нужный заголовок.
  //
  // здесь используется тот же page, который передали в login.
  // отдельную вкладку или новый браузер эта строка не создает.

await expect(page.locator("xpath=//*[text()='Текстовые поля']")).toBeVisible();
// эта строка проверяет, что на странице виден элемент с текстом "Текстовые поля".
// элемент ищем через xpath, а затем проверяем его видимость.
// разберем всю строку по частям.
//
// await
// ожидает завершения проверки, прежде чем выполнять следующую строку теста.
// проверка асинхронная: нужный элемент может появиться не сразу.
// например, приложение сначала загружает данные, а затем показывает содержимое.
// await позволяет дождаться результата этой проверки.
// при этом весь javascript не останавливается - ожидает именно текущая асинхронная функция.
// если проверка завершится с ошибкой, выполнение теста прервется на этой строке.
//
// expect(...)
// начинает проверку и получает то, что мы хотим проверить.
// здесь внутрь expect передаем локатор элемента.
// сам expect еще не определяет, какое условие нужно проверить.
// условие указываем дальше через .toBeVisible().
//
// page
// объект для управления вкладкой браузера, которую использует тест.
// через page можно открывать страницы, искать элементы и выполнять действия.
// здесь используем page для поиска элемента на текущей странице.
//
// .locator(...)
// метод, который создает локатор по переданной строке.
// локатор - описание того, как playwright должен найти элемент.
// создание локатора само по себе не проверяет, существует ли элемент.
// поиск выполняется, когда используем локатор для действия или проверки.
// здесь локатор используется в проверке .toBeVisible().
//
// "xpath=//*[text()='Текстовые поля']"
// вся запись внутри внешних двойных кавычек - строка javascript.
// эту строку передаем аргументом в page.locator().
// внешние двойные кавычки обозначают начало и конец строки в javascript.
// одинарные кавычки внутри относятся к текстовому значению в самом xpath.
// такое сочетание позволяет обойтись без экранирования кавычек.
//
// xpath=
// явно указывает playwright, что дальше записано выражение xpath.
// эта часть нужна playwright для выбора способа поиска.
// само выражение xpath начинается после знака равенства.
//
// //
// означает поиск на любой глубине документа.
// элемент не обязан находиться непосредственно внутри корневого элемента.
// он может быть вложен в другие элементы страницы.
//
// *
// означает любой тег.
// это может быть h1, h2, div, span, p или другой элемент.
// конкретный тег в этом локаторе не указан.
// поэтому xpath ищет по тексту среди всех элементов, а не только среди заголовков.
//
// [text()='Текстовые поля']
// квадратные скобки задают условие отбора элементов.
// из всех найденных элементов оставляем те, у которых подходит текст.
//
// text()
// выбирает непосредственные текстовые узлы элемента.
// это текст, который находится прямо внутри элемента, а не внутри его вложенных тегов.
// например, для <h1>Текстовые поля</h1> условие подойдет.
// для <h1><span>Текстовые поля</span></h1> условие подойдет к span, а не к h1.
//
// =
// сравнивает текстовый узел со строкой "Текстовые поля".
// если хотя бы один непосредственный текстовый узел точно совпадает, условие выполнено.
// регистр букв имеет значение.
// лишние пробелы и переносы строк внутри текстового узла тоже имеют значение.
// например, текст " Текстовые поля " не равен тексту "Текстовые поля".
// этот xpath сам не убирает пробелы по краям.
//
// .toBeVisible()
// задает условие проверки: найденный элемент должен быть видимым.
// одного присутствия элемента в DOM для этого недостаточно.
// если элемент скрыт, проверка не пройдет, пока он не станет видимым.
// playwright повторяет проверку в пределах настроенного таймаута.
// если элемент появится и станет видимым вовремя, проверка завершится успешно.
// если условие не выполнится до конца таймаута, тест упадет с ошибкой.
// отдельную фиксированную паузу перед такой проверкой обычно добавлять не нужно.
//
// локатор должен однозначно указывать на один элемент.
// если условию подходят несколько элементов, проверка может упасть из-за нескольких совпадений.
// тогда xpath нужно уточнить по тегу, атрибуту или родительскому элементу.
});

