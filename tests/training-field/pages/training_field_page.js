export class TrainingFieldPage {
  // export делает класс доступным для импорта в других файлах.
  // class объявляет класс - шаблон объекта с данными и методами.
  // TrainingFieldPage - имя нашего класса страницы.
  // хелпер сможет создать объект через new TrainingFieldPage(page).

    constructor(page) {
    // constructor вызывается автоматически при создании объекта через new.
    // page - параметр, через который получаем вкладку Playwright.
    // имя page выбираем сами, но здесь используем привычное название.
    // constructor не создает вкладку, а получает уже существующую.

    this.page = page;
    // this обозначает конкретный объект TrainingFieldPage.
    // this.page - свойство этого объекта для хранения вкладки.
    // точка дает доступ к свойству объекта.
    // знак = записывает значение справа в свойство слева.
    // page справа - вкладка, которую передали в constructor.
    // сохраняем ссылку на ту же вкладку, новую вкладку не создаем.
    // после этого методы класса смогут обращаться к ней через this.page.

    this.field = page.locator("xpath=//*[@id=\"training-field\"]");
    // this.field - свойство, в котором сохраняем локатор основного блока.
    // field - наше название свойства, специального значения у него нет.
    // page - вкладка, которую получили через параметр constructor.
    // locator - метод Playwright, который создает правило поиска элемента.
    // xpath= явно указывает использовать xpath для поиска.
    // "//" означает поиск по всему документу.
    // "*" означает элемент с любым названием тега.
    // @id обращается к HTML-атрибуту id.
    // условие @id="training-field" выбирает элемент с таким id.
    // \" записывает двойную кавычку внутри строки JavaScript.
    // в самом xpath обратных слешей уже не будет.
    // создание локатора не открывает сайт и не ждет появления элемента.

     this.textBoxCard = page.locator("xpath=//a[@id=\"tool-text-box\"]");
    // this.textBoxCard - свойство с локатором карточки тренажера.
    // textBoxCard - выбранное нами имя, по которому обратимся к локатору.
    // page.locator() создает локатор на переданной вкладке.
    // xpath= включает поиск через xpath.
    // "//a" выбирает ссылки - HTML-элементы с тегом a.
    // @id="tool-text-box" оставляет ссылку с нужным значением id.
    // этот локатор ищет карточку по id, текст карточки ему не нужен.


    this.textBoxHeading = page.locator("xpath=//h1[text()='Текстовые поля']");
    // this.textBoxHeading - свойство с локатором заголовка тренажера.
    // textBoxHeading - наше название этого свойства.
    // page.locator() создает правило поиска заголовка.
    // xpath= указывает способ поиска.
    // "//h1" выбирает элементы с тегом h1.
    // h1 - HTML-тег заголовка первого уровня.
    // text() выбирает непосредственные текстовые узлы заголовка.
    // знак = внутри xpath сравнивает значения, а не присваивает их.
    // "Текстовые поля" - текст, с которым сравниваем результат.
    // локатор сохраняется заранее, даже если заголовка пока нет на странице.
    // хелпер сможет использовать его для проверки после перехода.
  }

  async open() {
    // async объявляет асинхронный метод.
    // внутри такого метода можно использовать await.
    // вызов метода возвращает Promise - объект с будущим результатом.
    // open - наше имя метода открытия тренировочного поля.
    // параметры не передаем: вкладку уже сохранили в this.page.

    await this.page.goto("/practice");
    // await ждет завершения перехода перед продолжением метода.
    // this - текущий объект TrainingFieldPage.
    // this.page - вкладка, которую сохранили в constructor.
    // goto - метод Playwright для перехода по адресу.
    // "/practice" - путь страницы относительно baseURL из конфига.
    // при baseURL https://example.com откроется https://example.com/practice.
  }

  async openTextBox() {
    // async позволяет использовать await внутри метода.
    // openTextBox - наше имя метода перехода к тренажеру.
    // параметры не нужны: локатор карточки уже хранится в объекте.

    await this.textBoxCard.click();
    // await ждет завершения действия.
    // this.textBoxCard обращается к сохраненному локатору карточки.
    // click - метод Playwright для нажатия на элемент.
    // перед кликом Playwright ищет элемент по xpath из локатора.
    // затем ждет, чтобы элемент был видимым, стабильным,
    // доступным для нажатия и мог получить событие мыши.
    // после этого выполняет клик.
    // появление нужного заголовка отдельно проверяется в хелпере.
  }
}
