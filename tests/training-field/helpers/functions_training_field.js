

  //Страница хранит локаторы и действия

  //Хелпер связывает действия с ожидаемым результатом

  //Спека объявляет независимый тест

  //Спека файл с test, который называет самостоятельную проверку. Здесь это training-field.spec.js.

  //Страница файл с локаторами и действиями одного участка сайта. Здесь TrainingFieldPage знает, как открыть поле и карточку тренажера.

  //Класс шаблон объекта с данными и действиями. new TrainingFieldPage(page) создаст объект для текущей вкладки теста.

  //constructor метод класса, который получает page при создании объекта. this сохраняет page и локаторы внутри объекта.

  //Хелпер функция, которая собирает действия страницы и проверки в понятный флоу. Здесь runTrainingFieldCase вызывает методы страницы.

  //test.step именованный шаг внутри одного теста. Он помогает увидеть, на каком действии произошла ошибка.

  //Ассерт проверка ожидаемого состояния. expect(...).toBeVisible() дожидается видимого элемента.

  //Спека получает page и вызывает runTrainingFieldCase(page)

  //Хелпер создает TrainingFieldPage и называет два шага

  //Страница открывает /practice и нажимает #tool-text-box

  //Ассерты подтверждают открытие поля и заголовок тренажера

  import { test, expect } from "@playwright/test";
// import подключает то, что экспортируется из другого модуля.
// test - функция Playwright для объявления тестов.
// здесь используем ее метод test.step для именованных шагов.
// expect - функция, через которую задаем ожидаемый результат проверки.
// from указывает, откуда берем перечисленные имена.
// "@playwright/test" - имя установленного пакета Playwright.
// test и expect импортируются по своим именам.

  import { TrainingFieldPage } from "../pages/training_field_page.js";
// import подключает класс страницы из другого файла.
// TrainingFieldPage - имя класса, который там объявлен через export.
// from указывает путь к этому файлу.
// "../" поднимает нас из папки helpers в папку training-field.
// "pages/" переводит в папку с классами страниц.
// "training_field_page.js" - имя файла, из которого берем класс.
// импорт делает класс доступным, но объект страницы пока не создает.

  export async function runTrainingFieldCase(page) {
  // export позволяет импортировать эту функцию в спеку.
  // async объявляет асинхронную функцию и разрешает использовать await.
  // вызов такой функции возвращает Promise - объект с будущим результатом.
  // function объявляет функцию.
  // runTrainingFieldCase - наше имя функции, которая выполняет весь флоу.
  // page - параметр для вкладки Playwright, которую передаст спека.
  // функция работает с переданной вкладкой и сама новую не создает.

  const field = new TrainingFieldPage(page);
  // const объявляет переменную, которой нельзя присвоить другое значение.
  // field - наше имя переменной с объектом страницы.
  // знак = записывает в переменную результат выражения справа.
  // new создает новый объект на основе класса.
  // TrainingFieldPage - класс страницы, который импортировали выше.
  // page передаем в constructor этого класса.
  // constructor сохраняет вкладку и создает локаторы.
  // field теперь содержит объект с этими локаторами и методами.
  // сайт здесь еще не открывается: для этого отдельно вызовем open.

  await test.step("Шаг 1. Открыть тренировочное поле", async () => {
    // await ждет завершения всего шага перед продолжением функции.
    // test.step создает именованный шаг внутри текущего теста.
    // "Шаг 1. Открыть тренировочное поле" - название шага в отчете.
    // async объявляет асинхронную функцию с действиями этого шага.
    // эта функция не принимает параметры и не имеет отдельного имени.
    // test.step вызовет ее и дождется выполнения.
    // отдельный тест здесь не создается.

    await field.open();
    // await ждет завершения вызванного метода.
    // field - объект TrainingFieldPage, созданный выше.
    // точка дает доступ к его методу open.
    // open - наш метод, который вызывает page.goto("/practice").
    // вызов без аргументов: вкладка уже сохранена внутри объекта.

    await expect(field.field).toBeVisible();
    // await ждет завершения асинхронной проверки.
    // expect получает то, что будем проверять.
    // первое field - переменная с объектом TrainingFieldPage.
    // второе field после точки - свойство этого объекта с локатором.
    // field.field хранит локатор основного блока тренировочного поля.
    // toBeVisible - проверка Playwright на видимость элемента.
    // она повторяется автоматически до успеха или таймаута проверки.
    // если блок не станет видимым вовремя, шаг и текущий тест упадут.
  });

  await test.step("Шаг 2. Открыть текстовые поля", async () => {
    // await ждет завершения второго шага.
    // test.step добавляет еще один шаг в тот же тест.
    // "Шаг 2. Открыть текстовые поля" - его название в отчете.
    // async позволяет использовать await внутри функции этого шага.
    // второй шаг начнется после успешного завершения первого.
    // используем тот же объект field и ту же вкладку.

    await field.openTextBox();
    // await ждет завершения метода.
    // field - созданный ранее объект страницы.
    // openTextBox - наш метод перехода к тренажеру.
    // внутри него вызывается click у локатора карточки.
    // сам клик еще не является проверкой нужного заголовка.

    await expect(field.textBoxHeading).toBeVisible();
    // await ждет результата проверки.
    // expect получает локатор заголовка.
    // field - объект страницы.
    // textBoxHeading - его свойство с локатором заголовка "Текстовые поля".
    // toBeVisible проверяет, что найденный заголовок виден.
    // Playwright повторяет проверку до успеха или таймаута.
    // успешная проверка подтверждает появление заголовка тренажера.
    // если проверка упадет, упадет текущий тест, который вызвал хелпер.
  });
}
