import { test, expect } from "@playwright/test";
// Подключаем тест, шаги и проверку текста результата.
import { TextBoxPage } from "../text-box/pages/text_box_page.js";
// Берем уже готовую страницу из урока текстовых полей.
test.skip(process.env.RUN_FAILURE_DEMO !== "1", "Запускайте отдельно для разбора trace");
// Обычный запуск всего набора не должен падать специально.
test("учебное падение показывает неверное ожидаемое имя", async ({ page }) => {
// Начинаем отдельный тест с сохраненной сессией.
  const form = new TextBoxPage(page);
  // Создаем объект страницы для текущей вкладки.
  await test.step("Шаг 1. Открыть текстовые поля", async () => {
  // Даем переходу имя, которое появится в trace.
    await form.open();
    // Открываем тренажер через метод страницы.
    await expect(form.heading).toBeVisible();
    // Проверяем, что попали в нужный раздел.
  });
  // Закрываем первый шаг.
  await test.step("Шаг 2. Отправить имя и почту", async () => {
  // Заполняем форму заведомо известными данными.
    await form.submit("Иван Петров", "ivan@example.ru");
    // Страница введет значения и отправит форму.
  });
  // Закрываем второй шаг.
  await test.step("Шаг 3. Проверить результат", async () => {
  // Здесь намеренно проверяем неверное имя.
    await expect(form.result).toContainText("Мария");
    // На странице будет Иван Петров, поэтому этот ассерт создаст trace падения.
  });
  // Завершаем шаг проверки.
});
// Завершаем демонстрационный тест.
