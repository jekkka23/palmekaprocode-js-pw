//переменная - это контейнер для хранения данных. student - данные ученика. age - возраст

//const - обьявляет переменную которой нельзя присвоить другое значение. свойства обьекта внутри менять можно

//let - обьявляет переменную которой можно присвоить другое значение

//тип данных - это категория данных, которая определяет, какие операции можно выполнять с этими данными. В JavaScript есть несколько основных типов данных

//string - строка текст в кавычках , даже если внутри написаны цифры ""18

//number - число без кавычек 18

//boolean - логический тип данных, который может принимать только два значения: true (истина) или false (ложь)

//undefined - специальное значение, которое указывает на то, что переменная была объявлена, но ей не было присвоено никакого значения. Например, если вы создаете переменную без присвоения значения, она будет иметь значение undefined

//null - явно заданное отсутствие значения.

//object - обьект который обьединяет связанные значения под именами свойств. например на нашего студента это name email age

//if - выполняет код внутри фигурных скобок только токгдда когда условие true

// else - выполняет другой блок кода когда условие if дало false

//=== строго сравнивает значение вместе и их типами 18 === "18" дает false потому что один тип number другой string

//&& - логическое И, возвращает true только если оба условия true означает "и"

//>= - охначает больше или равно. например >= 18 дает тру для 18 и 17 но фолс для 17

//lenth - cвойство строки с числом символом. student.name.length > 0 проверяет что имя студента не пустое

//console.log - выводит текст в терминал. в браузере этой строки не видно

const student = {
  name: "Иван Петров",
  email: "ivan.petrov@example.com",
  age: 18,
  isActive: true
};
// создаем запись ученика : строки name и email, число age и логическое значение isActive

const expectedEmail = "ivan.petrov@example.com";
// отдельно создаем переменную с ожидаемым email для проверки

const hasName = student.name.length > 0;
// проверяем что имя студента не пустое


const isAbult = student.age >= 18;
// проверяем что возраст студента больше или равен 18

const emailMatches = student.email === expectedEmail;
// проверяем что email студента совпадает с ожидаемым email

const canStart = hasName && isAbult && emailMatches && student.isActive;
// проверяем что все условия выполнены: имя не пустое, возраст >= 18, email совпадает и студент активен

if (canStart) {
  console.log("Студент может начать обучение");
}
// если все условия выполнены, выводим сообщение что студент может начать обучение

else {
  console.log("Студент не может начать обучение");
}
// если хотя бы одно условие не выполнено, выводим сообщение что студент не может начать обучение


