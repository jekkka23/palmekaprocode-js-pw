// async - функция возвращает Promise

// function - объявляем функцию

// loadStudent - имя первой функции, по смыслу "загрузить ученика"

// checkStudent - имя второй функции, по смыслу "проверить ученика"

// shouldFail - параметр, который выбирает, создавать ли учебную ошибку

// false - логическое значение "нет"; здесь - не создавать ошибку

// true - логическое значение "да"; здесь - создать ошибку

// await - дождаться результата обещания

// setTimeout(300) - создать обещание, которое завершится после ожидания примерно 300 миллисекунд

// if - выполнить блок, если его условие считается истинным

// new Error("текст") - создать объект ошибки с сообщением

// throw - сообщить об ошибке и прервать обычное выполнение

// return - закончить функцию и отдать результат вызывающему коду

// { name: "Ирина", isActive: true } - объект с двумя свойствами

// name: "Ирина" - свойство name содержит строку "Ирина"

// isActive: true - свойство isActive содержит логическое значение true

// const student = ... - объявить переменную student и записать в нее полученный результат

// try - блок действий, во время которых может возникнуть ошибка

// catch (error) - блок обработки ошибки; пойманная ошибка доступна под именем error

// console.log(...) - вывести переданные значения в терминал

