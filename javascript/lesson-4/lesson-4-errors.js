import { setTimeout } from "node:timers/promises";
// Подключаем тот же встроенный таймер с Promise.
async function loadStudent(shouldFail) {
// При вызове получаем признак: вернуть данные или показать ошибку.
  await setTimeout(300);
  // Сначала ждем учебный ответ, как в первом примере.
  if (shouldFail) {
  // Когда shouldFail равен true, переходим в ветку ошибки.
    throw new Error("Не удалось получить ученика");
    // Создаем ошибку с понятным сообщением и прерываем функцию.
  }
  // Закрываем ветку ошибки; при false выполнение идет дальше.
  return { name: "Ирина", isActive: true };
  // При успешном результате возвращаем объект ученика.
}
// Закрываем функцию загрузки.
async function checkStudent(shouldFail) {
// Объявляем функцию, которая проверит оба возможных результата.
  try {
  // Начинаем блок, где загрузка может завершиться ошибкой.
    const student = await loadStudent(shouldFail);
    // Ждем ответ: только после успеха student получит объект.
    console.log("Ученик:", student.name);
    // При успехе печатаем имя; при ошибке эта строка не выполнится.
  } catch (error) {
  // Если ожидание завершилось ошибкой, получаем ее в error.
    console.log("Ошибка:", error.message);
    // Печатаем текст ошибки вместо имени ученика.
  }
  // Закрываем обработку успешного результата и ошибки.
}
// Закрываем функцию проверки.
await checkStudent(false);
// Первый вызов успешно напечатает имя ученика.
await checkStudent(true);
// Второй вызов завершится ошибкой и напечатает ее сообщение.
