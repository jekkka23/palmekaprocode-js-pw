import { setTimeout } from "node:timers/promises";
// Берем встроенный таймер Node.js, который возвращает Promise.
async function loadStudent() {
// Объявляем функцию: при вызове она вернет Promise с будущими данными.
  await setTimeout(300);
  // Ждем около 300 миллисекунд, имитируя медленный ответ.
  return { name: "Ирина", isActive: true };
  // После ожидания отдаем объект ученика как результат функции.
}
// Закрываем функцию: до вызова таймер еще не запускался.
console.log("До ожидания");
// Эта строка появится в терминале сразу.
const student = await loadStudent();
// Вызываем функцию и получаем объект только после завершения ее Promise.
console.log("После ожидания:", student.name);
// Печатаем имя из уже полученного объекта.
console.log("Активен:", student.isActive);
// Печатаем признак активности из того же объекта.
