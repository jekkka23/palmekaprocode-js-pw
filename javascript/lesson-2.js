const rows = [
// Создаем массив rows: в нем будут все строки учебной таблицы.
  { name: "Ирина", department: "QA" },
  // Первый объект: Ирина работает в QA.
  { name: "Максим", department: "Разработка" },
  // Второй объект: Максим работает в другом отделе.
  { name: "Олег", department: "QA" },
  // Третий объект: Олег тоже работает в QA.
];
// Закрываем массив: сейчас в rows три объекта.
const qaRows = rows.filter((row) => row.department === "QA");
// Проверяем department у каждого объекта: true дает QA, поэтому остаются Ирина и Олег.
const qaNames = qaRows.map((row) => row.name);
// Берем name у каждого из двух оставшихся объектов: получаем ["Ирина", "Олег"].
console.log("Всего строк:", rows.length);
// Печатаем 3: исходный массив по-прежнему содержит все строки.
console.log("Строк QA:", qaRows.length);
// Печатаем 2: после отбора остались два сотрудника QA.
console.log("Имена QA:", qaNames.join(", "));
// Соединяем имена через запятую и печатаем их в одной строке.
