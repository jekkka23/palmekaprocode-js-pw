//const сохраняет значение под именем. в этом примере под именем rows будет храниться весь набор строк

//свойства обьекта читаются через точку: student.name из урока по переменным, а в этом примере будет row.department

//строки пишутся в кавычках, а === проверяет точное совпаение

// {} - окружают свойства сотрудника name и department, а [] - окружают весь набор строк, в котором есть несколько сотрудников

//обьект - обьединяет свойство одной записи. например { name: 'Иван', department: 'Отдел продаж' }

//массив - хранит несколько значений по порядку внутри квадратных скобок.

//элемент массива - одно значение внутри массива . в нашем примере один элемент rows это одна строка таблицы

//filter - создает новый массив только из элементов, для которых условие вернуло true. исходный массив е меняется

//map - создает новый массив из элементов, которые были преобразованы функцией. исходный массив не меняется

//row - временное имя доя текущего элемента массива

//=> - запись короткой функции

//length - показывает количество элементов массива

//join - объединяет элементы массива в одну строку, между элементами ставится разделитель, который указан в скобках. если разделитель не указан, то будет запятая

//Выражение (row) => row.department === "QA" можно читать так: "возьми очередную строку и проверь ее отдел". JavaScript повторит эту проверку для всех объектов.
// Затем map пройдет только по оставшимся строкам и возьмет у каждой name. Так получатся два новых массива: объекты сотрудников QA и отдельно их имена.

//rows содержит три объекта в том же порядке, что и строки таблицы

//filter подставляет каждый объект в row, проверяет отдел и сохраняет совпадения в qaRows

//map проходит по qaRows и сохраняет значения name в qaNames

//length считает элементы каждого массива, а join превращает массив имен в текст для вывода


const rows = [
// Создаем массив rows: в нем будут все строки учебной таблицы.

  { name: "Ирина", department: "QA" },
  // Первый объект: Ирина работает в QA.

    { name: "Максим", department: "Разработка" },
  // Второй объект: Максим работает в другом отделе.

    { name: "Олег", department: "QA" },
  // Третий объект: Олег тоже работает в QA.

    { name: "Игорь", department: "QA" },
  // четвертый объект: Игорь тоже работает в QA.
  

];
// Закрываем массив: сейчас в rows три объекта.

const qaRows = rows.filter((row) => row.department === "QA");
// Проверяем department у каждого объекта: true дает QA, поэтому остаются Ирина и Олег.

const qaNames = qaRows.map((row) => row.name);
// Берем name у каждого из двух оставшихся объектов: получаем ["Ирина", "Олег, Игорь"].

const devRows = rows.filter((row) => row.department === "Разработка");

const devNames = devRows.map((row) => row.name);

console.log("Всего строк:", rows.length);
// Печатаем 3: исходный массив по-прежнему содержит все строки.

console.log("Строк разработки:", devRows.length);

console.log("Имена разработки:", devNames.join(", "));

console.log("Строк QA:", qaRows.length);
// Печатаем 2: после отбора остались два сотрудника QA.

console.log("Имена QA:", qaNames.join(", "));
// Соединяем имена через запятую и печатаем их в одной строке.

//РАЗБОР. Три проверки для трех объектов

//Условие row.department === "QA" выполняется отдельно для каждого сотрудника, в порядке записей массива.

//Ирина: department равно "QA". Сравнение дает true, строка остается.

//Максим: department равно "Разработка". Сравнение дает false, строка не попадает в qaRows.

