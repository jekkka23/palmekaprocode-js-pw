import { defineConfig } from "@playwright/test";
// import подключает в этот файл то, что экспортирует другой модуль.
// здесь подключаем функцию defineConfig из установленного пакета "@playwright/test".
// этот пакет дает нам Playwright Test: запуск тестов, вкладку page и проверки expect.
// пакет указан в package.json в корне проекта и устанавливается командой npm install.
// фигурные скобки { defineConfig } означают именованный импорт.
// мы берем конкретную функцию с именем defineConfig и дальше обращаемся к ней по этому имени.
// from указывает, откуда взять функцию. после from записано имя пакета в двойных кавычках.
// точка с запятой ; завершает инструкцию импорта.
// конфиг выполняется в Node.js, поэтому ниже можно обращаться к process.env.

export default defineConfig({
// здесь начинаем описывать настройки, которые Playwright прочитает перед запуском тестов.
// defineConfig вызывает функцию, которую подключили строкой выше.
// круглая скобка ( открывает список аргументов вызова функции.
// внутрь передаем один аргумент: объект с настройками тестового проекта.
// фигурная скобка { открывает этот объект. Его настройки записаны ниже.
// каждая настройка выглядит как имя: значение. Соседние настройки разделяются запятыми.
// defineConfig помогает редактору подсказывать названия настроек и подходящие значения.
// export отдает результат из этого файла наружу.
// default помечает его как основной экспорт файла: именно этот объект загрузит Playwright.
// сам запуск тестов происходит после чтения конфига, когда Playwright найдет спеки.

  testDir: "./tests",
  // testDir указывает папку, в которой Playwright будет искать тесты.
  // двоеточие : связывает имя настройки testDir с ее значением "./tests".
  // "./tests" - строка с относительным путем к папке.
  // точка . означает папку, где находится этот playwright.config.js.
  // этот конфиг лежит в intro/qa-playwright, поэтому тесты ищутся в intro/qa-playwright/tests.
  // Playwright также просматривает вложенные папки внутри указанной папки tests.
  // здесь он найдет training-field.spec.js и playwright-commands.spec.js.
  // запятая после строки отделяет testDir от следующей настройки use.

  use: {
  // use содержит общие настройки для встроенных объектов и возможностей Playwright.
  // например, здесь можно выбрать браузер и задать базовый адрес для вкладки page.
  // значение use - еще один объект, вложенный в основной объект конфига.
  // фигурная скобка { после двоеточия начинает именно этот вложенный объект.
  // baseURL и browserName ниже относятся к use, поэтому у них дополнительный отступ.
  // эти настройки применяются к каждому тесту, который запускается с этим конфигом.
  // благодаря этому одинаковые настройки задаем один раз для всех спек этой папки.

    baseURL: process.env.BASE_URL || "https://palmekaprocode.ru",
    // baseURL задает базовый адрес сайта для действий и проверок с относительным адресом.
    // например, page.goto("/login") использует этот адрес сайта и открывает страницу входа.
    // при базовом адресе "https://palmekaprocode.ru" получится https://palmekaprocode.ru/login.
    // expect(page).toHaveURL("/account") тоже использует baseURL для проверки полного адреса.
    // справа от двоеточия записано выражение, которое выбирает значение для baseURL.
    // process - встроенный объект Node.js с информацией о запущенном процессе.
    // env внутри process дает доступ к переменным окружения этого процесса.
    // BASE_URL - имя переменной окружения, которое мы выбрали для адреса сайта.
    // process.env.BASE_URL читает ее значение. Если переменная не задана, получаем undefined.
    // оператор || берет значение слева, если оно непустое, иначе берет значение справа.
    // поэтому без BASE_URL или при пустой строке используем "https://palmekaprocode.ru".
    // если в терминале задан другой адрес в BASE_URL, тесты будут использовать его.
    // выражение вычисляется при чтении конфига, и выбранный адрес становится значением baseURL.
    // двойные кавычки вокруг адреса означают, что это строка JavaScript.
    // запятая в конце отделяет baseURL от следующей настройки browserName.

    browserName: "chromium",
    // browserName выбирает тип браузера, в котором Playwright будет выполнять действия теста.
    // "chromium" - строковое значение, которое выбирает Chromium.
    // Playwright запускает свою установленную версию Chromium и создает в ней вкладку page.
    // параметр page в записи async ({ page }) дает тесту доступ к этой вкладке.
    // вызовы page.goto, page.locator и действия с найденными элементами работают в этой вкладке.
    // для установки нужного браузера используется команда npx playwright install chromium.
    // запятую после последней настройки объекта разрешает синтаксис JavaScript.
    // с ней удобно добавлять следующую настройку отдельной строкой.

  },
  // фигурная скобка } закрывает вложенный объект use.
  // это тот объект, который открыли в строке use: {.
  // baseURL и browserName теперь полностью описаны.
  // запятая после } относится к основному объекту: после use можно добавить другую настройку.

});
// фигурная скобка } закрывает основной объект с настройками testDir и use.
// круглая скобка ) завершает вызов defineConfig, которому передали этот объект.
// точка с запятой ; завершает инструкцию, начатую строкой export default defineConfig({.
// после загрузки этого файла Playwright знает, где искать тесты и как подготовить браузер.
// из корня проекта этот конфиг выбирается командой:
// npx playwright test --config intro/qa-playwright/playwright.config.js
// готовая короткая команда из корневого package.json делает тот же запуск: npm run test:first.
