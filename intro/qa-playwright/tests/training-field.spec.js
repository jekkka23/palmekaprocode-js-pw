//baseURL Общий адрес сайта в конфиге Playwright. Команда page.goto("/login") добавит к нему путь /login.

//Локатор Объект для поиска элемента на странице. В этом уроке page.locator получает готовую строку XPath.

//XPath Выражение для поиска элемента по тегу, атрибуту или тексту. Префикс xpath= явно выбирает этот способ поиска. 
//Пока используйте готовые выражения из примера; составлять свои научимся в отдельном блоке.

//Ассерт Проверка ожидаемого результата. expect(...).toBeVisible() проверяет, что найденный элемент виден.


//Разбираем конфиг с адресом сайта и браузером Chromium
