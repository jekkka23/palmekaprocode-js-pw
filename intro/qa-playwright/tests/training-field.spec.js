import { test, expect } from "@playwright/test";
// import подключает в эту спеку готовые функции из другого модуля.
// фигурные скобки { test, expect } означают именованный импорт двух функций.
// from указывает, откуда их взять.
// "@playwright/test" - npm-пакет Playwright, установленный в проекте через npm ci.
// test - функция, с помощью которой объявляем отдельный тест.
// первым аргументом передаем название теста, которое увидим в результате запуска.
// вторым аргументом передаем функцию с действиями и проверками этого теста.
// внутри нее открываем страницы, заполняем поля, нажимаем кнопки и проверяем результат.
// expect - функция, с которой начинается проверка ожидаемого результата.
// в expect передаем то, что проверяем: например, локатор элемента или вкладку page.
// после expect выбираем, что именно должно выполняться:
// toBeVisible() - элемент должен быть виден.
// toHaveValue("Анна") - поле должно содержать значение "Анна".
// toHaveURL("/account") - вкладка должна находиться по адресу кабинета.
// такие проверки пишем с await: Playwright ждет нужного состояния до таймаута.
// если ожидаемое состояние не появилось за отведенное время, тест завершится с ошибкой.


import { login } from "../../../tests/helpers/login.js";
// import подключает в эту спеку функцию из другого файла нашего проекта.
// login - наша функция входа в учебный аккаунт.
// она открывает страницу входа, заполняет почту и пароль, нажимает "Войти" и проверяет вход.
// фигурные скобки { login } означают именованный импорт:
// берем функцию, которую другой файл экспортирует под именем login.
//
// from указывает путь к файлу, из которого нужно взять функцию.
// "../../../tests/helpers/login.js" - относительный путь от текущей спеки.
// текущая спека находится в папке intro/qa-playwright/tests.
// каждый ../ поднимает нас на одну папку выше:
// первый ../ поднимает из intro/qa-playwright/tests в intro/qa-playwright.
// второй ../ поднимает из intro/qa-playwright в intro.
// третий ../ поднимает из intro в корень проекта.
// затем tests/helpers/login.js ведет из корня к файлу с функцией входа.
//
// после импорта функцию login можно вызвать внутри теста.
// строка await login(page) передает ей текущую вкладку браузера page.
// функция выполняет вход именно в этой вкладке.
// await ждет завершения функции, и после успешного входа тест продолжает работу.
// общий хелпер позволяет использовать один код входа в разных спеках.
// точка с запятой ; завершает инструкцию импорта.

test("учебный аккаунт открывает тренажер", async ({ page }) => {
// test объявляет один тест.
// строка в кавычках - название теста, которое увидим при запуске.
// async позволяет использовать await внутри функции теста.
// await нужен, чтобы дождаться завершения действия перед следующей строкой.
// { page } достает вкладку page из объекта, который передает Playwright.
// через page будем открывать страницы, искать элементы и взаимодействовать с ними.
// фигурная скобка после стрелки открывает тело теста: дальше пишем его действия и проверки.

  await login(page);
  // Хелпер открывает /login, вводит учетные данные и ждет кабинет
  console.log("вход выполнен");

  await page.locator("xpath=//header//a[@href='/practice']").click();
  // Находим ссылку на поле внутри верхнего меню по XPath и нажимаем ее.
  console.log("поле открыто");

  await page.locator("xpath=//a[@id='tool-text-box']").click();
  // Выбираем карточку "Текстовые поля" по XPath с ее id.
  console.log("карточка открыта");

  await expect(page.locator("xpath=//h1[normalize-space(.)='Текстовые поля']")).toBeVisible();
  // По XPath находим заголовок с нужным текстом и ждем, что он виден.
  console.log("заголовок виден");
});
